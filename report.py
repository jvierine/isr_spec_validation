"""Render concise comparison reports from the measured HDF5 results."""
import h5py
import json
from compare import ROOT,write_readme


def matrix_lines(g, links):
    names=g['code_names'].asstr()[:]
    m=g['pairwise_error'][:]
    labels={n:f'[{n}]({links[n]})' for n in names}
    lines=['| Code | '+' | '.join(labels[n] for n in names)+' |','|---|'+'---:|'*len(names)]
    for i,n in enumerate(names):
        cells=['—' if i==j else f'{"🟩" if x<=1e-6 else "🟥"} {x:.2e}' for j,x in enumerate(m[i])]
        lines.append('| '+labels[n]+' | '+' | '.join(cells)+' |')
    return lines+['']


def write_extended_results():
    lines=['# Additional comparisons','',
           '🟩 pass (error ≤ 10⁻⁶); 🟥 fail. Same metric as the README, with no fitted scaling.',
           'Click a code name to see its function call and numerical settings.',
           'Angles are measured from B. Parameters describe validation cases, not fitted observations.','']
    calls=['"""Exact calls for the displayed extended comparisons; generated by report.py.',
           '', 'Run: conda run -n base python invocations.py --case magnetic_42deg',
           'Add --code Swoboda to run one implementation. No tables are overwritten.',
           'Source URLs and checkout hashes are retained in each HDF5 provenance group.',
           '"""', 'import argparse', 'import h5py',
           'from compare import ROOT, ours, error',
           'from call_settings import run_swoboda, run_vierinen, run_analytic', '', '',
           'def frequency_grid(name):',
           "    with h5py.File(ROOT / 'tables/extended' / (name + '.h5')) as h:",
           "        return h['frequency_hz'][:]", '']
    case_names=[]
    for path in sorted((ROOT/'tables/extended').glob('*.h5')):
        with h5py.File(path) as h:
            # Choose the configured run, regardless of whether its metric passes.
            # Earlier settings stay in HDF5 for numerical-convergence auditing.
            g=h['refined'] if 'refined' in h else h
            assert path.stem.isidentifier()
            case_names.append(path.stem)
            calls+=['',f'def {path.stem}(code=None):']
            case=json.loads(h.attrs['parameters_json'])
            calls+=['    case = {']
            calls += [f'        {key!r}: {value!r},' for key,value in case.items()]
            calls+=['    }',
                    f"    case['frequency_hz'] = frequency_grid({path.stem!r})",
                    '    calls = {']
            links={}
            for name in g['code_names'].asstr()[:]:
                if name=='Kinetic': invocation='ours(case)'
                elif name=='Analytic': invocation='run_analytic(case)'
                elif name=='Swoboda':
                    invocation=(f"run_swoboda(case, quadrature_N={int(g.attrs.get('swoboda_quadrature_N',100))}, "
                                f"errF={float(g.attrs.get('swoboda_errF',1e-6))!r})")
                elif name=='Vierinen':
                    invocation=(f"run_vierinen(case, points={int(g.attrs.get('vierinen_points',20000))}, "
                                f"time_window_multiplier={int(g.attrs.get('vierinen_time_window_multiplier',1))})")
                else: raise ValueError(name)
                line_number=sum(s.count('\n')+1 for s in calls)+1
                links[name]=f'invocations.py#L{line_number}'
                calls.append(f'        {name!r}: lambda: {invocation},')
            calls+=['    }',
                    '    if code is not None and code not in calls:',
                    "        raise ValueError(f'{code} is not compared in this case')",
                    '    return {name: call() for name, call in calls.items()',
                    '            if code is None or name == code}', '']
            lines+=['## '+path.stem,'',
                    f"ne = {h.attrs['ne_m3']:g} m⁻³; Te = {h.attrs['te_K']:g} K; Ti = {h.attrs['ti_K']:g} K; vi = {h.attrs['vi_m_s']:g} m/s; "
                    f"B = {h.attrs['B_T']*1e6:g} μT; angle(k,B) = {h.attrs['angle_k_B_deg']:g}°; f_r = {h.attrs['f_r_MHz']:g} MHz. "
                    f"νen = {h.attrs['nu_en_s_1']:g} s⁻¹; νei = {h.attrs['nu_ei_s_1']:g} s⁻¹; νin = {h.attrs['nu_in_s_1']:g} s⁻¹.",
                    '']+matrix_lines(g,links)
    calls+=['',"if __name__ == '__main__':",
            '    parser = argparse.ArgumentParser()',
            f"    parser.add_argument('--case', required=True, choices={case_names!r})",
            "    parser.add_argument('--code', choices=['Kinetic','Swoboda','Vierinen','Analytic'])",
            '    args = parser.parse_args()',
            '    values = globals()[args.case](args.code)',
            "    with h5py.File(ROOT / 'tables/extended' / (args.case + '.h5')) as h:",
            "        group = h['refined'] if 'refined' in h else h",
            '        for name, components in values.items():',
            "            difference = error(components[-1], group[name + '/S_total'][:])",
            "            print(name, 'error against saved spectrum:', difference)",
            "            if difference > 1e-6: raise RuntimeError('Saved spectrum not reproduced')", '']
    (ROOT/'invocations.py').write_text('\n'.join(calls))
    (ROOT/'EXTENDED_RESULTS.md').write_text('\n'.join(lines))


def main():
    with h5py.File(ROOT/'tables/comparison/summary.h5') as h: write_readme(h['worst_pairwise_error'][:])
    write_extended_results()


if __name__=='__main__': main()
